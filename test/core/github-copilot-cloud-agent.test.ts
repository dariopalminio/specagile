/** SpecAgile: the agent's name, description and title back to OpenSpec's. */
function withOpenSpecAgentName(content: string): string {
  return AGENT_IDENTITY_REPLACEMENTS.reduce(
    (result, [upstream, fork]) => result.split(fork).join(upstream),
    content
  );
}

/**
 * SpecAgile: a generated file as OpenSpec wrote it (upstream's package, CLI
 * and agent name). Earlier output, which the fork refreshes and removes like
 * its own.
 */
function asOpenSpecWroteIt(content: string): string {
  return withUpstreamIdentity(withOpenSpecAgentName(content))
    .split('npm install -g specagile')
    .join('npm install -g @fission-ai/openspec')
    .split('`specagile` CLI')
    .join('`openspec` CLI');
}

