  describe('cloud opt-in', () => {
    const CONFIG_WITH_COMMENTS = `schema: spec-driven

# Project context (optional)
context: |
  Tech stack: TypeScript
`;

    async function writeConfig(content: string): Promise<string> {
      const configPath = getConfigFile(tempDir);
      await fs.mkdir(path.dirname(configPath), { recursive: true });
      await fs.writeFile(configPath, content);
      return configPath;
    }

    describe('readCopilotCloudOptIn', () => {
      it('returns undefined when there is no config', () => {
        expect(readCopilotCloudOptIn(tempDir)).toBeUndefined();
      });

      it('reads an explicit opt-in and opt-out', async () => {
        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: true\n`);
        expect(readCopilotCloudOptIn(tempDir)).toBe(true);

        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: false\n`);
        expect(readCopilotCloudOptIn(tempDir)).toBe(false);
      });

      it('treats a non-boolean value as undecided', async () => {
        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: "yes"\n`);
        expect(readCopilotCloudOptIn(tempDir)).toBeUndefined();
      });
    });

    describe('persistCopilotCloudOptIn', () => {
      it('writes the nested key while preserving existing comments and content', async () => {
        const configPath = await writeConfig(CONFIG_WITH_COMMENTS);

        await persistCopilotCloudOptIn(tempDir, true);

        const written = await fs.readFile(configPath, 'utf8');
        expect(written).toContain('# Project context (optional)');
        expect(written).toContain('Tech stack: TypeScript');
        expect(parse(written)).toMatchObject({
          schema: 'spec-driven',
          githubCopilot: { cloudAgent: true },
        });
        // Round-trips through the reader.
        expect(readCopilotCloudOptIn(tempDir)).toBe(true);
      });

      it('flips an existing decision in place', async () => {
        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: true\n`);
        await persistCopilotCloudOptIn(tempDir, false);
        expect(readCopilotCloudOptIn(tempDir)).toBe(false);
      });

      it('is a no-op when no config file exists', async () => {
        await persistCopilotCloudOptIn(tempDir, true);
        await expect(
          fs.stat(getConfigFile(tempDir))
        ).rejects.toMatchObject({ code: 'ENOENT' });
      });

      it('persists into and reads from config.yml when only .yml exists', async () => {
        const ymlPath = getConfigYmlFile(tempDir);
        await fs.mkdir(path.dirname(ymlPath), { recursive: true });
        await fs.writeFile(ymlPath, `${CONFIG_WITH_COMMENTS}`);

        await persistCopilotCloudOptIn(tempDir, true);

        // No sibling .yaml was created; the .yml file was edited in place.
        await expect(
          fs.stat(getConfigFile(tempDir))
        ).rejects.toMatchObject({ code: 'ENOENT' });
        const written = await fs.readFile(ymlPath, 'utf8');
        expect(written).toContain('# Project context (optional)');
        expect(written).toContain('cloudAgent: true');
        expect(readCopilotCloudOptIn(tempDir)).toBe(true);
      });

      it('does not throw on a scalar-content config and writes a valid map', async () => {
        // A degenerate config whose top-level node is a bare scalar used to
        // throw "Expected a YAML collection as document contents".
        await writeConfig('null\n');
        await expect(persistCopilotCloudOptIn(tempDir, false)).resolves.toBeUndefined();
        expect(readCopilotCloudOptIn(tempDir)).toBe(false);
      });

      it('does not throw on a sequence-root config and writes a valid map', async () => {
        // A YAML list at the root is also not a map: setIn would throw, so it
        // must be replaced with a fresh document rather than crash.
        await writeConfig('- a\n- b\n');
        await expect(persistCopilotCloudOptIn(tempDir, true)).resolves.toBeUndefined();
        expect(readCopilotCloudOptIn(tempDir)).toBe(true);
      });

      it('leaves an unparseable config untouched instead of throwing', async () => {
        // A multi-document stream can't be edited without corrupting it; persist
        // must skip it (no throw, no clobber) rather than crash.
        const malformed = '---\na: 1\n---\nb: 2\n';
        const configPath = await writeConfig(malformed);

        await expect(persistCopilotCloudOptIn(tempDir, true)).resolves.toBeUndefined();

        expect(await fs.readFile(configPath, 'utf8')).toBe(malformed);
      });

      it('does not throw when the githubCopilot node itself is not a map', async () => {
        // Root is a valid map, but `githubCopilot` holds a scalar/null/sequence:
        // descending into it with setIn used to throw. Each must be replaced
        // with a map, keeping the rest of the config (and its comments) intact.
        for (const bad of [
          'githubCopilot: false',
          'githubCopilot: null',
          'githubCopilot:\n  - a\n  - b',
        ]) {
          await writeConfig(`schema: spec-driven\n# keep me\n${bad}\n`);
          await expect(persistCopilotCloudOptIn(tempDir, true)).resolves.toBeUndefined();
          expect(readCopilotCloudOptIn(tempDir)).toBe(true);
          const written = await fs.readFile(
            getConfigFile(tempDir),
            'utf8'
          );
          expect(written).toContain('# keep me');
          expect(written).toContain('schema: spec-driven');
        }
      });
    });

    describe('listManagedCloudFiles', () => {
      it('is empty on a clean project and lists managed files after a write', async () => {
        await expect(listManagedCloudFiles(tempDir)).resolves.toEqual([]);
        await writeCopilotCloudFiles(tempDir);
        await expect(listManagedCloudFiles(tempDir)).resolves.toEqual([
          COPILOT_CLOUD_FILES.setupSteps,
          COPILOT_CLOUD_FILES.agent,
        ]);
      });

      it('excludes a user-owned (non-managed) file', async () => {
        await writeCopilotCloudFiles(tempDir);
        await fs.writeFile(
          path.join(tempDir, COPILOT_CLOUD_FILES.setupSteps),
          'name: my own build workflow\n'
        );
        await expect(listManagedCloudFiles(tempDir)).resolves.toEqual([COPILOT_CLOUD_FILES.agent]);
      });
    });

    describe('findUnmanagedCloudFiles', () => {
      it('is empty on a clean project and after a managed write', async () => {
        await expect(findUnmanagedCloudFiles(tempDir)).resolves.toEqual([]);
        await writeCopilotCloudFiles(tempDir);
        await expect(findUnmanagedCloudFiles(tempDir)).resolves.toEqual([]);
      });

      it('reports a user-owned (non-managed) file that would be left untouched', async () => {
        const setupStepsPath = path.join(tempDir, COPILOT_CLOUD_FILES.setupSteps);
        await fs.mkdir(path.dirname(setupStepsPath), { recursive: true });
        await fs.writeFile(setupStepsPath, 'name: my own build workflow\n');

        await expect(findUnmanagedCloudFiles(tempDir)).resolves.toEqual([
          COPILOT_CLOUD_FILES.setupSteps,
        ]);
      });
    });

    describe('hasExistingManagedCloudFiles', () => {
      it('is false on a clean project', async () => {
        await expect(hasExistingManagedCloudFiles(tempDir)).resolves.toBe(false);
      });

      it('is true when a managed file exists, false for a purely customized one', async () => {
        await writeCopilotCloudFiles(tempDir);
        await expect(hasExistingManagedCloudFiles(tempDir)).resolves.toBe(true);

        // Replace both managed files with customized content: no longer "managed".
        await fs.writeFile(
          path.join(tempDir, COPILOT_CLOUD_FILES.setupSteps),
          'name: my own workflow\n'
        );
        await fs.writeFile(
          path.join(tempDir, COPILOT_CLOUD_FILES.agent),
          'my own agent instructions\n'
        );
        await expect(hasExistingManagedCloudFiles(tempDir)).resolves.toBe(false);
      });
    });

    describe('isCopilotCloudEnabled', () => {
      it('honors an explicit opt-out even when managed files exist', async () => {
        await writeCopilotCloudFiles(tempDir);
        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: false\n`);
        await expect(isCopilotCloudEnabled(tempDir)).resolves.toBe(false);
      });

      it('honors an explicit opt-in with no files yet', async () => {
        await writeConfig(`${CONFIG_WITH_COMMENTS}githubCopilot:\n  cloudAgent: true\n`);
        await expect(isCopilotCloudEnabled(tempDir)).resolves.toBe(true);
      });

      it('falls back to existing managed files when undecided (migration)', async () => {
        await writeCopilotCloudFiles(tempDir);
        await expect(isCopilotCloudEnabled(tempDir)).resolves.toBe(true);
      });

      it('is false when undecided and no managed files exist', async () => {
        await expect(isCopilotCloudEnabled(tempDir)).resolves.toBe(false);
      });
    });
  });
