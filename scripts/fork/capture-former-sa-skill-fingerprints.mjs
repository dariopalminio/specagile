#!/usr/bin/env node
/**
 * Writes src/core/fork/former-sa-skill-fingerprints.ts: the fingerprints of
 * every SKILL.md text a SpecAgile release installed under a name it no longer
 * uses (FORMER_SA_SKILL_NAMES: `sa-verify`), for `former-skills.ts` to
 * recognize as SpecAgile's.
 *
 * From 2.1, SpecAgile installs the skills from the `skills/` folder of its
 * repository at the release's tag, so an installed copy is the text that tag
 * holds, or, in a tool's own folder, what `projectSkillText` makes of it. The
 * script reads `skills/<name>/SKILL.md` at each tag in RELEASE_TAGS with
 * `git show` and fingerprints both forms the way
 * `src/core/shared/generated-fingerprint.ts` does. No release after 6.0.0
 * writes those names, so the list is closed.
 *
 *   pnpm build && node scripts/fork/capture-former-sa-skill-fingerprints.mjs
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** Every release that installed a name in FORMER_SA_SKILL_NAMES. */
const RELEASE_TAGS = ['v2.1.1', 'v2.1.2', 'v3.0.0', 'v3.0.1', 'v4.0.0', 'v5.0.0', 'v6.0.0'];

const root = fileURLToPath(new URL('../../', import.meta.url));
const load = (rel) => import(pathToFileURL(path.join(root, 'dist', rel)).href);

const { FORMER_SA_SKILL_NAMES } = await load('core/fork/identity.js');
const { AI_TOOLS } = await load('core/config.js');
const { projectSkillText } = await load('core/skill-installer.js');
const { fingerprintGeneratedContent } = await load('core/shared/generated-fingerprint.js');

const show = (tag, file) => {
  try {
    return execFileSync('git', ['show', `${tag}:${file}`], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    throw new Error(`${tag} has no ${file} (is the tag fetched?): ${error.stderr ?? error.message}`);
  }
};

const fingerprints = new Set();
for (const name of FORMER_SA_SKILL_NAMES) {
  for (const tag of RELEASE_TAGS) {
    const published = show(tag, `skills/${name}/SKILL.md`).replace(/\r\n/g, '\n');
    fingerprints.add(fingerprintGeneratedContent(published));
    for (const tool of AI_TOOLS) fingerprints.add(fingerprintGeneratedContent(projectSkillText(tool.value, published)));
  }
}

const lines = [
  '// Generated by scripts/fork/capture-former-sa-skill-fingerprints.mjs. Do not edit.',
  '//',
  '// Fingerprints of every SKILL.md text a SpecAgile release installed under a',
  "// name it no longer uses, in .agents/skills and in each tool's folder: the",
  "// release tag's skills/<name>/SKILL.md and its projectSkillText forms.",
  `// Skills: ${FORMER_SA_SKILL_NAMES.join(', ')}`,
  `// Tags: ${RELEASE_TAGS.join(', ')}`,
  'export const FORMER_SA_SKILL_FINGERPRINTS: readonly string[] = [',
  ...[...fingerprints].sort().map((fingerprint) => `  '${fingerprint}',`),
  '];',
  '',
];
const out = path.join(root, 'src', 'core', 'fork', 'former-sa-skill-fingerprints.ts');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${fingerprints.size} fingerprints to ${path.relative(root, out)}`);
