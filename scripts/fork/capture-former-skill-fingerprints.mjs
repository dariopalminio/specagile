#!/usr/bin/env node
/**
 * Writes src/core/fork/former-release-fingerprints.ts: the fingerprints of
 * every `openspec-*` SKILL.md text a checkout wrote, for `former-skills.ts` to
 * recognize as OpenSpec's once the running version's text has moved on.
 *
 * Run it against a built checkout of the release to capture:
 *
 *   git worktree add ../former 0039e6b3     # the fork before the rename (OpenSpec 2.0.0 + specify/plan)
 *   cd ../former && pnpm install && pnpm build && cd -
 *   node scripts/fork/capture-former-skill-fingerprints.mjs ../former
 *
 * It renders each skill for every set of installed workflows (the release's
 * own `everySkillRendering`), both as the shared `.agents/skills` copy and as
 * each tool's own copy, and fingerprints them the way
 * `src/core/shared/generated-fingerprint.ts` does.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const checkout = path.resolve(process.argv[2] ?? '');
if (!process.argv[2]) {
  console.error('Usage: node scripts/fork/capture-former-skill-fingerprints.mjs <built checkout>');
  process.exit(1);
}
const load = (rel) => import(pathToFileURL(path.join(checkout, 'dist', rel)).href);

const { everySkillRendering } = await load('core/shared/skill-generation.js');
const { AI_TOOLS, OPENSPEC_SKILL_NAMES } = await load('core/config.js');
const { getTransformerForTool, transformToSharedSkillReferences } = await load('utils/command-references.js');
const { resolveCommandInvocation, resolveCommandSurfaceCapability } = await load('core/command-surface.js');
const { fingerprintGeneratedContent } = await load('core/shared/generated-fingerprint.js');
const { version } = (await import(pathToFileURL(path.join(checkout, 'package.json')).href, { with: { type: 'json' } })).default;

const transformers = [
  transformToSharedSkillReferences,
  ...AI_TOOLS.map((tool) =>
    getTransformerForTool(tool.value, 'skills', resolveCommandSurfaceCapability(tool.value), resolveCommandInvocation(tool.value))
  ),
];

const fingerprints = new Set();
for (const name of OPENSPEC_SKILL_NAMES) {
  if (!name.startsWith('openspec-')) throw new Error(`${checkout} already has the fork's names (${name})`);
  for (const transformer of transformers) {
    for (const text of everySkillRendering(name, version, transformer)) fingerprints.add(fingerprintGeneratedContent(text));
  }
}

const lines = [
  '// Generated by scripts/fork/capture-former-skill-fingerprints.mjs. Do not edit.',
  '//',
  `// Fingerprints of every \`openspec-*\` SKILL.md text the fork wrote before the`,
  `// rename (version ${version}, the same templates as OpenSpec ${version}), for`,
  '// every installed workflow set, in .agents/skills and in each tool\'s folder.',
  '// Upstream\'s RELEASED_GENERATED_FINGERPRINTS stop at 1.16.1.',
  `// Skills: ${OPENSPEC_SKILL_NAMES.join(', ')}`,
  'export const FORMER_RELEASE_FINGERPRINTS: readonly string[] = [',
  ...[...fingerprints].sort().map((fingerprint) => `  '${fingerprint}',`),
  '];',
  '',
];
const out = path.join(root, 'src', 'core', 'fork', 'former-release-fingerprints.ts');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${fingerprints.size} fingerprints to ${path.relative(root, out)}`);
