function replaceRequired(
  content: string,
  searchValue: string,
  replaceValue: string,
  label: string
): string {
  if (!content.includes(searchValue)) {
    throw new Error(`Cannot build Copilot cloud file content: missing ${label}`);
  }
  return content.replace(searchValue, replaceValue);
}

